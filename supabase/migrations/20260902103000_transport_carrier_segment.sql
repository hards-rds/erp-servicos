alter table public.payables add column transport_trip_id uuid;
alter table public.payables
  add constraint payables_transport_trip_company_fk
  foreign key (company_id, transport_trip_id) references public.transport_trips(company_id, id);

create index transport_vehicles_company_status_idx on public.transport_vehicles(company_id, status, plate);
create index transport_drivers_company_status_idx on public.transport_drivers(company_id, status, full_name);
create index transport_trips_company_status_date_idx on public.transport_trips(company_id, status, scheduled_departure_at desc);
create index transport_trip_documents_trip_idx on public.transport_trip_documents(company_id, trip_id);
