begin;

alter table public.companies
  drop constraint if exists companies_service_segment_check;

alter table public.companies
  add constraint companies_service_segment_check
  check (service_segment in ('tecnologia', 'otica', 'escola_futebol', 'transportadora', 'generico'));

create table public.transport_vehicles (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id),
  plate text not null,
  renavam text,
  registry_state text not null,
  vehicle_kind text not null check (vehicle_kind in ('tracao', 'reboque', 'utilitario', 'outro')),
  body_type text,
  make text,
  model text,
  model_year integer check (model_year is null or model_year between 1950 and 2200),
  color text,
  rntrc text,
  ownership text not null default 'proprio' check (ownership in ('proprio', 'arrendado', 'terceiro')),
  owner_name text,
  owner_document text,
  tare_kg numeric(14,3) check (tare_kg is null or tare_kg >= 0),
  capacity_kg numeric(14,3) check (capacity_kg is null or capacity_kg >= 0),
  capacity_m3 numeric(14,3) check (capacity_m3 is null or capacity_m3 >= 0),
  odometer_km numeric(14,1) check (odometer_km is null or odometer_km >= 0),
  licensing_expires_at date,
  insurance_expires_at date,
  status text not null default 'ativo' check (status in ('ativo', 'manutencao', 'inativo')),
  notes text,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, id),
  unique (company_id, plate)
);

create table public.transport_drivers (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id),
  full_name text not null,
  document text not null,
  cnh_number text not null,
  cnh_category text not null,
  cnh_expires_at date not null,
  phone text,
  email text,
  employment_type text not null default 'proprio' check (employment_type in ('proprio', 'agregado', 'terceiro')),
  status text not null default 'ativo' check (status in ('ativo', 'afastado', 'inativo')),
  emergency_contact text,
  notes text,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, id),
  unique (company_id, document),
  unique (company_id, cnh_number)
);

create table public.transport_trips (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id),
  trip_number bigint generated by default as identity,
  client_id uuid,
  sender_client_id uuid,
  recipient_client_id uuid,
  vehicle_id uuid not null,
  trailer_id uuid,
  driver_id uuid not null,
  status text not null default 'planejada' check (status in ('planejada', 'carregamento', 'em_transito', 'entregue', 'cancelada')),
  cargo_description text not null,
  cargo_type text,
  cargo_quantity numeric(14,3) check (cargo_quantity is null or cargo_quantity >= 0),
  gross_weight_kg numeric(14,3) not null default 0 check (gross_weight_kg >= 0),
  cargo_value numeric(14,2) not null default 0 check (cargo_value >= 0),
  freight_value numeric(14,2) not null check (freight_value >= 0),
  toll_value numeric(14,2) not null default 0 check (toll_value >= 0),
  insurance_value numeric(14,2) not null default 0 check (insurance_value >= 0),
  other_costs numeric(14,2) not null default 0 check (other_costs >= 0),
  origin_city text not null,
  origin_state text not null,
  origin_city_code text not null,
  destination_city text not null,
  destination_state text not null,
  destination_city_code text not null,
  scheduled_departure_at timestamptz not null,
  scheduled_arrival_at timestamptz,
  departed_at timestamptz,
  delivered_at timestamptz,
  distance_km numeric(14,1) check (distance_km is null or distance_km >= 0),
  payer_role text not null default 'remetente' check (payer_role in ('remetente', 'destinatario', 'expedidor', 'recebedor', 'outros')),
  operational_notes text,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, id),
  unique (company_id, trip_number),
  constraint transport_trips_client_fk foreign key (company_id, client_id) references public.clients(company_id, id),
  constraint transport_trips_sender_fk foreign key (company_id, sender_client_id) references public.clients(company_id, id),
  constraint transport_trips_recipient_fk foreign key (company_id, recipient_client_id) references public.clients(company_id, id),
  constraint transport_trips_vehicle_fk foreign key (company_id, vehicle_id) references public.transport_vehicles(company_id, id),
  constraint transport_trips_trailer_fk foreign key (company_id, trailer_id) references public.transport_vehicles(company_id, id),
  constraint transport_trips_driver_fk foreign key (company_id, driver_id) references public.transport_drivers(company_id, id),
  check (trailer_id is null or trailer_id <> vehicle_id),
  check (scheduled_arrival_at is null or scheduled_arrival_at >= scheduled_departure_at)
);

create table public.transport_trip_documents (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id),
  trip_id uuid not null,
  document_type text not null default 'nfe' check (document_type in ('nfe', 'nf', 'declaracao', 'outro')),
  access_key text,
  number text,
  series text,
  issuer_document text,
  issuer_name text,
  document_value numeric(14,2) check (document_value is null or document_value >= 0),
  gross_weight_kg numeric(14,3) check (gross_weight_kg is null or gross_weight_kg >= 0),
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  constraint transport_trip_documents_trip_fk foreign key (company_id, trip_id) references public.transport_trips(company_id, id) on delete cascade,
  unique (company_id, access_key),
  check (access_key is null or access_key ~ '^[0-9]{44}$')
);

create table public.cte_documents (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id),
  trip_id uuid not null,
  client_id uuid,
  environment text not null default 'homologacao' check (environment in ('homologacao', 'producao')),
  model text not null default '57' check (model = '57'),
  series integer not null default 1 check (series between 1 and 999),
  document_number bigint,
  status text not null default 'rascunho' check (status in ('rascunho', 'validado', 'enfileirado', 'autorizado', 'rejeitado', 'cancelado')),
  modal text not null default 'rodoviario' check (modal in ('rodoviario')),
  service_type text not null default 'normal' check (service_type in ('normal', 'subcontratacao', 'redespacho', 'redespacho_intermediario', 'multimodal')),
  operation_nature text not null,
  cfop text not null,
  issue_state text not null,
  freight_value numeric(14,2) not null check (freight_value >= 0),
  amount_receivable numeric(14,2) not null check (amount_receivable >= 0),
  components jsonb not null default '[]'::jsonb,
  sender_data jsonb not null default '{}'::jsonb,
  recipient_data jsonb not null default '{}'::jsonb,
  payer_data jsonb not null default '{}'::jsonb,
  cargo_data jsonb not null default '{}'::jsonb,
  tax_data jsonb not null default '{}'::jsonb,
  access_key text,
  protocol text,
  rejection_message text,
  request_payload jsonb,
  response_payload jsonb,
  authorized_xml text,
  issued_at timestamptz,
  canceled_at timestamptz,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, id),
  constraint cte_documents_trip_fk foreign key (company_id, trip_id) references public.transport_trips(company_id, id),
  constraint cte_documents_client_fk foreign key (company_id, client_id) references public.clients(company_id, id),
  unique (company_id, series, document_number),
  unique (company_id, access_key),
  check (access_key is null or access_key ~ '^[0-9]{44}$')
);

alter table public.financial_entries add column transport_trip_id uuid;
alter table public.financial_entries add column cte_document_id uuid;
