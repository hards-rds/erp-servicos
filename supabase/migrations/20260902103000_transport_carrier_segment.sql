insert into public.permissions (module, action, scope)
select module, action, 'company'
from (
  values
    ('transporte.frota', 'visualizar'), ('transporte.frota', 'criar'), ('transporte.frota', 'editar'), ('transporte.frota', 'excluir'),
    ('transporte.motoristas', 'visualizar'), ('transporte.motoristas', 'criar'), ('transporte.motoristas', 'editar'), ('transporte.motoristas', 'excluir'),
    ('transporte.viagens', 'visualizar'), ('transporte.viagens', 'criar'), ('transporte.viagens', 'editar'), ('transporte.viagens', 'excluir'),
    ('fiscal.cte', 'visualizar'), ('fiscal.cte', 'criar'), ('fiscal.cte', 'editar'), ('fiscal.cte', 'excluir'), ('fiscal.cte', 'emitir'), ('fiscal.cte', 'cancelar')
) as transport_permissions(module, action)
on conflict (module, action, scope) do nothing;

insert into public.group_permissions (group_id, permission_id)
select group_record.id, permission_record.id
from public.groups group_record
join public.permissions permission_record
  on permission_record.module in ('transporte.frota', 'transporte.motoristas', 'transporte.viagens', 'fiscal.cte')
where group_record.name = 'Master Geral'
   or (group_record.name in ('Administração', 'Administracao') and permission_record.action in ('visualizar', 'criar', 'editar', 'excluir', 'emitir', 'cancelar'))
   or (group_record.name = 'Operação' and permission_record.module like 'transporte.%' and permission_record.action in ('visualizar', 'criar', 'editar'))
   or (group_record.name = 'Fiscal' and permission_record.module = 'fiscal.cte' and permission_record.action in ('visualizar', 'criar', 'editar', 'emitir', 'cancelar'))
   or (group_record.name = 'Financeiro' and permission_record.module in ('transporte.viagens', 'fiscal.cte') and permission_record.action = 'visualizar')
on conflict do nothing;

create or replace function public.seed_transport_permissions_for_group()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.group_permissions (group_id, permission_id)
  select new.id, permission_record.id
  from public.permissions permission_record
  where permission_record.module in ('transporte.frota', 'transporte.motoristas', 'transporte.viagens', 'fiscal.cte')
    and (
      new.name = 'Master Geral'
      or (new.name in ('Administração', 'Administracao') and permission_record.action in ('visualizar', 'criar', 'editar', 'excluir', 'emitir', 'cancelar'))
      or (new.name = 'Operação' and permission_record.module like 'transporte.%' and permission_record.action in ('visualizar', 'criar', 'editar'))
      or (new.name = 'Fiscal' and permission_record.module = 'fiscal.cte' and permission_record.action in ('visualizar', 'criar', 'editar', 'emitir', 'cancelar'))
      or (new.name = 'Financeiro' and permission_record.module in ('transporte.viagens', 'fiscal.cte') and permission_record.action = 'visualizar')
    )
  on conflict do nothing;
  return new;
end;
$$;

drop trigger if exists groups_seed_transport_permissions on public.groups;
create trigger groups_seed_transport_permissions
after insert on public.groups
for each row execute function public.seed_transport_permissions_for_group();

commit;
